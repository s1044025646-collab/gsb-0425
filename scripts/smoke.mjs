process.env.IMA_DB_PATH = "data/smoke.db";
const { Store } = await import("../dist/src/store.js");
const { startServer } = await import("../dist/src/server.js");
const store = new Store(process.env.IMA_DB_PATH);
const { port, close } = await startServer(store, 0);
console.log("port", port);
const j = async (r) => ({ status: r.status, body: await r.json() });
let r = await fetch(`http://127.0.0.1:${port}/contexts`, {method:"POST",headers:{"content-type":"application/json"},body:JSON.stringify({initialPredictor:0,initialIndex:0})});
const ctx = await r.json(); console.log("create", ctx.id);
r = await fetch(`http://127.0.0.1:${port}/contexts/${ctx.id}/blocks`, {method:"POST",headers:{"content-type":"application/json"},body:JSON.stringify({blockId:"b1",encoding:"hex",data:"77",nibbleCount:2})});
console.log("append", await j(r));
r = await fetch(`http://127.0.0.1:${port}/contexts/${ctx.id}/samples`);
console.log("samples", await j(r));
r = await fetch(`http://127.0.0.1:${port}/explain`, {method:"POST",headers:{"content-type":"application/json"},body:JSON.stringify({predictor:0,index:0,nibble:15})});
console.log("explain", await j(r));
r = await fetch(`http://127.0.0.1:${port}/contexts/${ctx.id}/pcm`);
const buf = Buffer.from(await r.arrayBuffer());
console.log("pcm bytes", buf.length, "samples", buf.length/2, [...buf]);
r = await fetch(`http://127.0.0.1:${port}/contexts/${ctx.id}/derive`, {method:"POST",headers:{"content-type":"application/json"},body:"{}"});
console.log("derive", (await j(r)).body.initialPredictor);
close(); store.close();
